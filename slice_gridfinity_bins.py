#!/usr/bin/env python3
"""Slice all generated Gridfinity STL files into G-code using OrcaSlicer CLI.

This script expects the STL library to be generated by `generate_gridfinity_bins.py`
and the merged OrcaSlicer preset JSON files to live in `orca-settings/`.

Default behavior:
- scan the `bins/` tree for `.stl` files
- slice each one with the configured OrcaSlicer process/printer/filament profiles
- write `.gcode` next to the corresponding STL
- skip files that already have a `.gcode` output

Example:
    python3 slice_gridfinity_bins.py
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path


ORCA_SLICER = "orcaslicer"


def collect_stl_files(root: Path) -> list[Path]:
    if not root.exists():
        return []
    return sorted(p for p in root.rglob("*.stl") if p.is_file())


def build_profile_list(profile_dir: Path, filenames: list[str]) -> str:
    profiles = []
    for name in filenames:
        path = profile_dir / name
        if not path.exists():
            raise FileNotFoundError(f"Profile not found: {path}")
        profiles.append(str(path))
    return ";".join(profiles)


def determine_gcode_path(stl_path: Path) -> Path:
    return stl_path.with_suffix(".gcode")


def slice_stl(
    slicer_path: str,
    stl_path: Path,
    settings_list: str,
    filament_list: str,
    dry_run: bool,
    force: bool,
) -> bool:
    gcode_path = determine_gcode_path(stl_path)
    if gcode_path.exists() and not force:
        print(f"Skipping existing G-code: {gcode_path}")
        return False

    if dry_run:
        print(f"Would slice: {stl_path} -> {gcode_path}")
        return True

    cmd = [
        slicer_path,
        str(stl_path),
        "--load-settings",
        settings_list,
        "--load-filaments",
        filament_list,
        "--slice",
        "0",
        "--outputdir",
        str(stl_path.parent),
    ]

    print("$", " ".join(cmd))
    subprocess.run(cmd, check=True)

    if gcode_path.exists():
        print(f"Created: {gcode_path}")
        return True

    fallback = stl_path.with_suffix(".gcode")
    if fallback.exists():
        print(f"Created: {fallback}")
        return True

    raise FileNotFoundError(f"Slicing completed but no G-code file was produced for: {stl_path}")


def run_slicing(
    stl_root: Path,
    profile_dir: Path,
    settings_files: list[str],
    filament_files: list[str],
    dry_run: bool,
    force: bool,
) -> int:
    settings_list = build_profile_list(profile_dir, settings_files)
    filament_list = build_profile_list(profile_dir, filament_files)

    stl_files = collect_stl_files(stl_root)
    if not stl_files:
        print(f"No STL files found under {stl_root}")
        return 0

    sliced = 0
    for stl_path in stl_files:
        if slice_stl(
            slicer_path=ORCA_SLICER,
            stl_path=stl_path,
            settings_list=settings_list,
            filament_list=filament_list,
            dry_run=dry_run,
            force=force,
        ):
            sliced += 1

    print(f"Completed: {sliced} STL file(s) sliced")
    return 0


def default_profile_lists(repo_root: Path) -> tuple[list[str], list[str]]:
    return ["process.json", "machine.json"], ["filament.json"]


def main() -> int:
    repo_root = Path(__file__).resolve().parent
    default_stl_root = repo_root / "bins"
    default_profile_dir = repo_root / "orca-settings"

    parser = argparse.ArgumentParser(
        description="Slice Gridfinity STL files with OrcaSlicer using the merged repo-local presets."
    )
    parser.add_argument(
        "--input-root",
        type=Path,
        default=default_stl_root,
        help="Root folder containing the generated STL files (default: ./bins)",
    )
    parser.add_argument(
        "--profile-dir",
        type=Path,
        default=default_profile_dir,
        help="Folder containing the OrcaSlicer preset JSON files (default: ./orca-settings)",
    )
    parser.add_argument(
        "--settings",
        nargs="*",
        default=None,
        help="Comma-free list of process/machine preset JSON files to load. Default: process.json machine.json",
    )
    parser.add_argument(
        "--filaments",
        nargs="*",
        default=None,
        help="Comma-free list of filament preset JSON files to load. Default: filament.json",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print slice operations without writing G-code files",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite existing `.gcode` files when they already exist",
    )
    args = parser.parse_args()
    profile_settings, profile_filaments = default_profile_lists(repo_root)
    settings_files = args.settings if args.settings is not None else profile_settings
    filament_files = args.filaments if args.filaments is not None else profile_filaments

    try:
        return run_slicing(
            stl_root=args.input_root,
            profile_dir=args.profile_dir,
            settings_files=settings_files,
            filament_files=filament_files,
            dry_run=args.dry_run,
            force=args.force,
        )
    except FileNotFoundError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
    except subprocess.CalledProcessError as exc:
        print(f"OrcaSlicer failed with exit code {exc.returncode}", file=sys.stderr)
        return exc.returncode


if __name__ == "__main__":
    raise SystemExit(main())
